"""Writes src/MacroPad.App/Themes/Icons.axaml from Material Design Icons (Apache 2.0, https://pictogrammers.com).

Usage: npm pack @mdi/js@7.4.47 && tar xzf mdi-js-7.4.47.tgz, then python make-icons.py package/mdi.js
Each icon becomes a StreamGeometry resource "Icon.<Name>" for a PathIcon (24×24 view box). Add names to ICONS and run
it again; the names are the @mdi/js ones without the "mdi" prefix.
"""
import re
import sys
from pathlib import Path

ICONS = """
Keyboard KeyboardOutline MusicNote VolumeHigh Mouse LightningBolt LightbulbOutline Usb Bluetooth PowerPlugOffOutline
TrayArrowDown TrayArrowUp CogOutline RotateRight RotateLeft PencilOutline GestureTap Plus TrashCanOutline Export Import
PaletteOutline Monitor HomeAssistant Speaker Update InformationOutline Refresh Dialpad LayersOutline CircleSmall
ChevronRight Check Close ContentCopy ArrowUDownLeft AccountBoxOutline
""".split()

source = Path(sys.argv[1]).read_text(encoding="utf-8")
paths = dict(re.findall(r'export var mdi(\w+) = "([^"]+)";', source))
missing = [n for n in ICONS if n not in paths]
if missing:
    sys.exit(f"Not in @mdi/js: {', '.join(missing)}")

out = Path(__file__).resolve().parents[2] / "src/MacroPad.App/Themes/Icons.axaml"
lines = [
    '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
    "    <!-- Generated by tools/icons/make-icons.py from Material Design Icons (Apache 2.0). Don't edit by hand. -->",
]
lines += [f'    <StreamGeometry x:Key="Icon.{n}">{paths[n]}</StreamGeometry>' for n in sorted(ICONS)]
lines.append("</ResourceDictionary>")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(ICONS)} icons to {out}")
